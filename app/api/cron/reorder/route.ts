import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/db";
import { generateInvoiceNumber } from "@/lib/utils";
import { checkCronSecret } from "@/lib/cron-auth";

export async function GET(req: NextRequest) {
  const auth = checkCronSecret(req);
  if (auth) return auth;
  try {
    const medicines = await prisma.medicine.findMany({
      select: { id: true, reorderLevel: true, reorderQuantity: true, supplierId: true },
    });

    const reorderMap = new Map(
      medicines
        .filter((m) => m.reorderQuantity > 0 && m.supplierId)
        .map((m) => [m.id, m])
    );

    if (reorderMap.size === 0) {
      return NextResponse.json({ created: 0, message: "No medicines configured for reorder" });
    }

    const inventory = await prisma.inventory.findMany({
      where: {
        medicineId: { in: Array.from(reorderMap.keys()) },
      },
      include: { medicine: true, branch: true },
    });

    const lowStock = inventory.filter((item) => {
      const config = reorderMap.get(item.medicineId);
      return config && item.quantity <= config.reorderLevel;
    });

    if (lowStock.length === 0) {
      return NextResponse.json({ created: 0, message: "No low-stock items" });
    }

    const owner = await prisma.user.findFirst({
      where: { role: "OWNER" },
      select: { id: true },
    });

    if (!owner) {
      return NextResponse.json({ error: "No owner user found" }, { status: 500 });
    }

    const groups = new Map<string, (typeof lowStock)[0][]>();
    for (const item of lowStock) {
      const key = `${item.branchId}:${item.medicine.supplierId}`;
      if (!groups.has(key)) groups.set(key, []);
      groups.get(key)!.push(item);
    }

    // ponytail: naive dedupe — skip any medicine that already has an open auto-reorder PO, so repeated cron runs don't stack POs
    const medicineIds = lowStock.map((i) => i.medicineId);
    const openPOItems = await prisma.purchaseOrderItem.findMany({
      where: {
        medicineId: { in: medicineIds },
        po: { status: { in: ["DRAFT", "PENDING", "ORDERED"] } },      },
      select: { medicineId: true },
      distinct: ["medicineId"],
    });
    const alreadyOrdered = new Set(openPOItems.map((i) => i.medicineId));
    for (const [key, items] of groups) {
      groups.set(key, items.filter((i) => !alreadyOrdered.has(i.medicineId)));
    }
    for (const key of [...groups.keys()]) {
      if (groups.get(key)!.length === 0) groups.delete(key);
    }
    if (groups.size === 0) {
      return NextResponse.json({ created: 0, message: "All low-stock items already have open POs" });
    }

    const createdPOs: { poId: string; poNumber: string; items: number }[] = [];
    const notifications: { userId: string; message: string }[] = [];

    for (const [key, items] of groups) {
      const [branchId, supplierId] = key.split(":");
      const itemsData = items.map((item) => {
        const qty = item.medicine.reorderQuantity;
        const price = item.medicine.purchasePrice;
        return {
          medicineId: item.medicineId,
          quantity: qty,
          unitPrice: price,
          gstRate: item.medicine.gstRate,
          totalAmount: qty * price,
        };
      });
      const subtotal = itemsData.reduce((sum, i) => sum + i.totalAmount, 0);
      const gstTotal = itemsData.reduce((sum, i) => sum + (i.totalAmount * i.gstRate) / 100, 0);

      const po = await prisma.purchaseOrder.create({
        data: {
          poNumber: await generateInvoiceNumber("PO"),
          branchId,
          supplierId,
          createdById: owner.id,
          status: "DRAFT",
          notes: "Auto-generated by reorder cron",
          subtotal,
          taxableAmount: subtotal,
          cgstAmount: gstTotal / 2,
          sgstAmount: gstTotal / 2,
          totalAmount: subtotal + gstTotal,
          items: { create: itemsData },
        },
      });

      createdPOs.push({ poId: po.id, poNumber: po.poNumber, items: itemsData.length });

      const branchManagers = await prisma.user.findMany({
        where: { branchId, role: { in: ["MANAGER", "OWNER"] } },
        select: { id: true },
      });

      for (const manager of branchManagers) {
        notifications.push({
          userId: manager.id,
          message: `Auto-reorder created PO ${po.poNumber} for ${items.length} item(s) in ${items[0].branch.name}`,
        });
      }
    }

    if (notifications.length > 0) {
      await prisma.notification.createMany({
        data: notifications.map((n) => ({
          ...n,
          type: "REORDER",
          title: "Auto-Reorder PO Created",
          channels: JSON.stringify(["email"]),
          entityType: "purchase_order",
        })),
      });
    }

    return NextResponse.json({
      created: createdPOs.length,
      purchaseOrders: createdPOs,
    });
  } catch (error) {
    console.error("Error generating reorder POs:", error);
    return NextResponse.json({ error: "Failed to generate reorder POs" }, { status: 500 });
  }
}
